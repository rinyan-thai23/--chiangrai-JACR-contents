## ⚠️ 訪問前に必ず確認したいこと

営業時間、料金、道路、国境、登山路、船、季節イベントは変更されることがあります。

記事内の情報だけで判断せず、訪問当日に施設、行政機関、国立公園、交通事業者の案内を確認してください。

雨季は増水、落石、ぬかるみ、乾季は日差し、乾燥、煙霧が旅程へ影響する場合があります。

自然スポットでは閉鎖の判断に従い、柵を越えたり、許可のない場所へ入ったりしないでください。

